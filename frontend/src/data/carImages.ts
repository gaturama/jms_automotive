export const getCarImages = (carName: string): any[] => {
  const rawKey = carName
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_|_$/g, "");

  const key = carKeyMap[rawKey] || rawKey;

  return carImages[key] || [];
};
